// Builds desktop/assets/browser/browser_viewer.html: viewer.js and the pinned
// noVNC as one inlined classic script. loadHtmlString has no base URL, so a
// module, an import or a second file would not load on every native webview.
// Run `npm ci && node build.mjs` here after changing viewer.js or a version.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build } from 'esbuild';

const here = fileURLToPath(new URL('.', import.meta.url));
const output = new URL('../../assets/browser/browser_viewer.html', import.meta.url);

// noVNC probes H.264 with a top-level await, which a classic script cannot
// hold. The flag is a live binding read only when encodings are sent, after
// the handshake, so the probe resolves into it instead. Xvnc sends no H.264.
const probe = 'supportsWebCodecsH264Decode = await _checkWebCodecsH264DecodeSupport();';
const noTopLevelAwait = {
  name: 'no-top-level-await',
  setup(b) {
    b.onLoad({ filter: /novnc[\\/]core[\\/]util[\\/]browser\.js$/ }, async ({ path }) => {
      const source = readFileSync(path, 'utf8');
      if (!source.includes(probe)) throw new Error('noVNC changed its H.264 probe; update build.mjs');
      return {
        contents: source.replace(probe, '_checkWebCodecsH264DecodeSupport().then((s) => { supportsWebCodecsH264Decode = s; });'),
      };
    });
  },
};

export async function buildViewerHtml() {
  const result = await build({
    stdin: {
      contents: "import RFB from '@novnc/novnc'; import { startViewer } from './viewer.js'; startViewer(RFB, window);",
      resolveDir: here,
    },
    bundle: true,
    format: 'iife',
    minify: true,
    target: 'es2020',
    legalComments: 'none',
    plugins: [noTopLevelAwait],
    write: false,
  });
  const script = result.outputFiles[0].text;
  // The HTML parser would end the script at the first `</script`.
  if (/<\/script/i.test(script)) throw new Error('bundle contains </script');
  return `<!doctype html>
<!-- Generated by desktop/tool/browser_viewer/build.mjs; do not edit. -->
<!-- noVNC (MPL-2.0, https://github.com/novnc/noVNC) with pako (MIT, https://github.com/nodeca/pako). -->
<html>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<style>html, body, #screen { margin: 0; width: 100%; height: 100%; overflow: hidden; }</style>
</head>
<body>
<div id="screen"></div>
<script>${script}</script>
</body>
</html>
`;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(output, await buildViewerHtml());
}
