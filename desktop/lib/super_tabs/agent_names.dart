/// A name from [agentNames] no agent in [taken] has (case aside), picked at random; when all are taken, any of them.
String freshAgentName(Iterable<String> taken, [Random? random]) {
  final used = {for (final name in taken) name.toLowerCase()};
  final free = [
    for (final name in agentNames)
      if (!used.contains(name.toLowerCase())) name,
  ];
  final pool = free.isEmpty ? agentNames : free;
  return pool[(random ?? Random()).nextInt(pool.length)];
}
