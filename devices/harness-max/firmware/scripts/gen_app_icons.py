#!/usr/bin/env python3
"""Pre-render the apps' own icons at the exact sizes Harness Max's pages draw them (no runtime scaling, so they stay
crisp), as the Pro's scripts/pod_gen_logos.py does for the engines' logos.

    python3 scripts/gen_app_icons.py            # needs Pillow; run from anywhere

Reads V3's icons (devices/harness-max/flutter/assets/apps/<file>.png) whole: each is its own rounded tile, drawn as
V3's AppIcon draws it. Resizes each with LANCZOS (alpha kept) to every size below. Writes main/app/max_ui_icons.{c,h}:
per app and size an RGB565 array in native order (what ht_pro_image wants) and an alpha8 array, each glass's sizes
under its own HT_HEIGHT so a build carries only its own.

The sizes: the pages draw an app's icon DY(n) px square for each n in DESIGN (design px of V3's 1480 x 320 canvas; DY
in main/app/max_ui_draw.h), on each glass in HEIGHTS. Keep both in step with the pages: test_max_view.c's
test_app_icons fails at either height when a page draws Harness at a size not made here.
"""
from pathlib import Path
from PIL import Image

# V3's keys (app_icon.dart appIconAsset: lower case, letters and digits only) and each one's file; the other names V3
# gives the same app share its pictures.
APPS = {
    "harness": "harness.png",
    "orca": "orca.png",
    "herdr": "herdr.png",
    "vscode": "visual-studio-code.png",
    "cursor": "cursor.png",
    "claude": "claude.png",
    "chatgpt": "chatgpt.png",
    "terminal": "terminal.png",
}
ALIASES = {"visualstudiocode": "vscode", "code": "vscode", "claudedesktop": "claude", "codex": "chatgpt"}
DESIGN = {
    22: "Inbox: a notice's app (max_ui_lists.c NOTE_ICON)",
    28: "Attention: the agent's app (max_ui_card.c AT_ICON)",
    60: "App Detail's app column (max_ui_overview.c APP_ICON)",
    72: "an Apps card (max_ui_lists.c APP_ICON_D)",
}
HEIGHTS = [480, 415]   # the ESP32-P4's glass and the demo bar's

here = Path(__file__).resolve().parent
fw = here.parent
src = fw.parent / "flutter" / "assets" / "apps"
dest = fw / "main" / "app"


def dy(n: int, height: int) -> int:
    """max_ui_draw.h's DY(n) on a glass `height` px tall: MAX_Y(n * 3 / 2), in C's integer arithmetic."""
    return (n * 3 // 2) * height // 480


def rgb565(im: Image.Image) -> list:
    return [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) for r, g, b, _ in zip(*[iter(im.tobytes())] * 4)]


def main() -> None:
    c = ["// Generated by scripts/gen_app_icons.py from devices/harness-max/flutter/assets/apps. Do not edit.",
         "// px is RGB565 in native order (what ht_pro_image wants), a is alpha; one pre-rendered pair per size, only",
         "// the sizes of the glass this build is for.",
         '#include "max_ui_icons.h"', ""]
    rows = []
    total = {}
    for i, height in enumerate(HEIGHTS):
        c.append(f"#{'if' if i == 0 else 'elif'} HT_HEIGHT == {height}")
        rows.append(f"#{'if' if i == 0 else 'elif'} HT_HEIGHT == {height}")
        total[height] = 0
        for app, file in APPS.items():
            im = Image.open(src / file).convert("RGBA")
            for s in sorted({dy(n, height) for n in DESIGN}):
                r = im.resize((s, s), Image.LANCZOS)
                name = f"i_{app}_{s}"
                c.append(f"static const uint16_t {name}_px[{s * s}] = {{{','.join(map(str, rgb565(r)))}}};")
                c.append(f"static const uint8_t {name}_a[{s * s}] = {{{','.join(map(str, r.getchannel('A').tobytes()))}}};")
                for key in [app] + [k for k, v in ALIASES.items() if v == app]:
                    rows.append(f'    {{"{key}", {{{name}_px, {name}_a, {s}, {s}, 0, NULL}}}},')
                total[height] += s * s * 3
    c.append("#endif")
    rows.append("#endif")
    c += ["", "const max_icon_t max_icons[] = {"] + rows + ["    {NULL, {NULL, NULL, 0, 0, 0, NULL}},", "};", ""]
    (dest / "max_ui_icons.c").write_text("\n".join(c))
    (dest / "max_ui_icons.h").write_text("\n".join([
        "#pragma once", "// Generated by scripts/gen_app_icons.py. Do not edit.", '#include "pro_canvas.h"', "",
        "// An app's own icon at one size: app is V3's key for it (lower case, letters and digits only).",
        "typedef struct { const char *app; ht_pro_bitmap_t image; } max_icon_t;",
        "// Every icon of this build's glass at each size its pages draw, ended by {NULL}.",
        "extern const max_icon_t max_icons[];", ""]))
    for height in HEIGHTS:
        print(f"{height}: sizes {sorted({dy(n, height) for n in DESIGN})}, flash bytes (px + alpha) {total[height]}")


if __name__ == "__main__":
    main()
