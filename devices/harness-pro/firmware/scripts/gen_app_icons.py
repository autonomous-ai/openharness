#!/usr/bin/env python3
"""Bake the Apps screen's app icons and card colours into the firmware (no runtime scaling or colour maths).

    python3 scripts/gen_app_icons.py [--check]   # needs Pillow; run from anywhere

Reads each app's official icon (.github/assets/apps/<id>.png, square RGBA, any size of at least 72 px; ids in APPS).
Icon: cropped to its alpha >= 128 box (the tile, not the macOS drop shadow), padded square with transparency, resized
with LANCZOS to every size in SIZES; alpha < 64 is then cleared so the shadow leaves no grey haze on a coloured card.
Card colour: measured on the source as given, opaque pixels only (alpha >= 250): the most frequent saturated colour
when saturated pixels cover >= 10 % of them, else the most frequent dark-mark colour, else the Pro's own dark. A
near-black colour is lifted to the charcoal; then R, G and B are scaled down together only until white reads at 4.5:1
on the colour as RGB565 decodes it (what the panel shows). The bottom of the gradient is that top at half brightness.
Writes main/pod/app_icons.{c,h}: per app and size an RGB565 array in native order (what ht_pro_image wants) and an
alpha8 array, a table and pod_app_style(). --check writes nothing and fails when the committed files are stale.
"""
import sys
from collections import Counter
from pathlib import Path
from PIL import Image

# cli/src/cable/hosts/hostDetect.ts NAMES order; "harness" and "terminal" get no card. codex is ChatGPT.
APPS = ("orca herdr rex zellij tmux kitty wezterm iterm terminal-app ghostty cmux vscode cursor warp claude codex "
        "opencode").split()
SIZES = (72, 44)
CHARCOAL = (0x3A, 0x3A, 0x3F)   # the mockup's dark gradient top
PRO_DARK = (0x55, 0x55, 0x5C)   # PH_TINT_OTHER1, for an icon with no colour of its own
NEAR_BLACK = 0.012              # relative luminance under which a card would read as a hole in the screen
MIN_CONTRAST = 4.5

here = Path(__file__).resolve().parent
fw = here.parent
SRC = fw.parents[2] / ".github" / "assets" / "apps"
DEST = fw / "main" / "pod"
HEADER = "// Generated by scripts/gen_app_icons.py from .github/assets/apps/*.png. Do not edit."
STALE = "app_icons.{c,h} are stale: run scripts/gen_app_icons.py"


def encode565(rgb) -> int:
    r, g, b = rgb
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def decode565(v: int) -> tuple:
    r5, g6, b5 = v >> 11, (v >> 5) & 0x3F, v & 0x1F
    return (r5 << 3 | r5 >> 2, g6 << 2 | g6 >> 4, b5 << 3 | b5 >> 2)


def luminance(rgb) -> float:
    """WCAG relative luminance."""
    lin = [c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4 for c in (v / 255 for v in rgb)]
    return 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2]


def contrast_white(rgb) -> float:
    return 1.05 / (luminance(rgb) + 0.05)


def measure(im: Image.Image) -> tuple:
    px = [(r, g, b) for r, g, b, a in zip(*[iter(im.tobytes())] * 4) if a >= 250]
    saturated = [p for p in px if max(p) / 255 >= 0.25 and (max(p) - min(p)) / max(p) >= 0.35]
    if px and len(saturated) * 10 >= len(px):
        return Counter(saturated).most_common(1)[0][0]
    dark = [p for p in px if 0.2126 * p[0] + 0.7152 * p[1] + 0.0722 * p[2] < 128]
    return Counter(dark).most_common(1)[0][0] if dark else PRO_DARK


def card_colours(measured) -> tuple:
    base = CHARCOAL if luminance(measured) < NEAR_BLACK else measured
    for k in range(100, -1, -1):   # k = 0 is black, which white always reads on
        top = encode565(tuple(round(c * k / 100) for c in base))
        if contrast_white(decode565(top)) >= MIN_CONTRAST:
            break
    return top, encode565(tuple(c // 2 for c in decode565(top)))


def icon(im: Image.Image, size: int) -> tuple:
    im = im.crop(im.getchannel("A").point(lambda a: 255 if a >= 128 else 0).getbbox())
    side = max(im.size)
    sq = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    sq.paste(im, ((side - im.width) // 2, (side - im.height) // 2))
    pixels = list(zip(*[iter(sq.resize((size, size), Image.LANCZOS).tobytes())] * 4))
    return [encode565(p[:3]) for p in pixels], bytes(a if a >= 64 else 0 for *_, a in pixels)


def render(src: Path) -> tuple:
    unknown = sorted(p.name for p in src.glob("*.png") if p.stem not in APPS)
    if unknown:
        raise ValueError(f"{src}: not an app id in APPS: {', '.join(unknown)}")
    c = [HEADER, "// px is RGB565 in native order (what ht_pro_image wants), a is alpha; one pre-rendered pair per size.",
         "#include <string.h>", '#include "app_icons.h"', ""]
    rows = []
    for app in APPS:
        path = src / f"{app}.png"
        if not path.exists():
            continue
        im = Image.open(path).convert("RGBA")
        cid = app.replace("-", "_")
        measured = measure(im)
        top, bottom = card_colours(measured)
        hexc = lambda rgb: "#%02X%02X%02X" % rgb
        c.append(f"// {app}: measured {hexc(measured)}, "
                 f"top {hexc(decode565(top))} {contrast_white(decode565(top)):.2f}:1, "
                 f"bottom {hexc(decode565(bottom))} {contrast_white(decode565(bottom)):.2f}:1")
        for s in SIZES:
            px, alpha = icon(im, s)
            c.append(f"static const uint16_t a_{cid}_{s}_px[{s * s}] = {{{','.join(map(str, px))}}};")
            c.append(f"static const uint8_t a_{cid}_{s}_a[{s * s}] = {{{','.join(map(str, alpha))}}};")
            c.append(f"static const pod_app_icon_t a_{cid}_{s} = {{a_{cid}_{s}_px, a_{cid}_{s}_a, {s}}};")
        rows.append(f'    {{"{app}", {{&a_{cid}_72, &a_{cid}_44, 0x{top:04X}, 0x{bottom:04X}}}}},')
    c += ["", "static const struct { const char *id; pod_app_style_t style; } rows[] = {"] + rows + ["};", "",
          "const pod_app_style_t *pod_app_style(const char *app_id) {", "    if (!app_id) return NULL;",
          "    for (size_t i = 0; i < sizeof rows / sizeof rows[0]; i++)",
          "        if (!strcmp(rows[i].id, app_id)) return &rows[i].style;", "    return NULL;", "}", ""]
    h = [HEADER, "#pragma once", "#include <stdint.h>",
         "typedef struct { const uint16_t *rgb565; const uint8_t *alpha; uint16_t size; } pod_app_icon_t;",
         "typedef struct { const pod_app_icon_t *icon72, *icon44; uint16_t card_top, card_bottom; } pod_app_style_t;",
         "const pod_app_style_t *pod_app_style(const char *app_id);   "
         "// NULL for NULL, an unknown id or an app with no icon", ""]
    return "\n".join(c), "\n".join(h)


def main(argv: list, src: Path = SRC, dest: Path = DEST) -> int:
    c, h = render(src)
    out = {dest / "app_icons.c": c, dest / "app_icons.h": h}
    if "--check" in argv:
        if all(p.exists() and p.read_text() == text for p, text in out.items()):
            return 0
        print(STALE, file=sys.stderr)
        return 1
    for p, text in out.items():
        p.write_text(text)
    baked = sum(1 for app in APPS if (src / f"{app}.png").exists())
    print("app icon bytes (px + alpha):", baked * sum(s * s * 3 for s in SIZES))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
