def bake():
    lv = [(b >> k) & 3 for b in SPARK for k in (6, 4, 2, 0)]
    a = lambda x, y: lv[y * W + x] * 85 if 0 <= x < W and 0 <= y < H else 0
    out = []
    for oy in range(OH):
        for ox in range(OW):
            fx, fy = (ox + .5) * W / OW - .5, (oy + .5) * H / OH - .5
            x0, y0 = int(fx // 1), int(fy // 1)
            tx, ty = fx - x0, fy - y0
            v = (a(x0, y0) * (1 - tx) + a(x0 + 1, y0) * tx) * (1 - ty) + (a(x0, y0 + 1) * (1 - tx) + a(x0 + 1, y0 + 1) * tx) * ty
            out.append(min(255, int(v + .5)))
    rows = [', '.join(f'{v:3d}' for v in out[y * OW:(y + 1) * OW]) for y in range(OH)]
    return ('// Generated by scripts/gen_ph_spark.py from the round\'s ht_spark: do not edit.\n#pragma once\n#include <stdint.h>\n\n'
            f'enum {{ PH_SPARK_W = {OW}, PH_SPARK_H = {OH} }};\nstatic const uint8_t PH_SPARK_ALPHA[PH_SPARK_W * PH_SPARK_H] = {{\n'
            + ''.join(f'    {r},\n' for r in rows) + '};\n')

text = bake()
if '--check' in sys.argv:
    sys.exit(0 if os.path.exists(OUT) and open(OUT).read() == text else 'ph_spark.h is stale: run scripts/gen_ph_spark.py')
open(OUT, 'w').write(text)
