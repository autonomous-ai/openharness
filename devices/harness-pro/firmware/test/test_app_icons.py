#!/usr/bin/env python3
"""App icons and card colours (scripts/gen_app_icons.py -> main/pod/app_icons.{c,h}).

GeneratorTests prove the generator's rules on synthetic art built here, so they run with no source art present."""
import contextlib
import importlib.util
import io
import subprocess
import tempfile
import unittest
from pathlib import Path

from PIL import Image

PRO = Path(__file__).resolve().parents[1]
_spec = importlib.util.spec_from_file_location("gen_app_icons", PRO / "scripts" / "gen_app_icons.py")
gen = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(gen)

HEADER = "// Generated by scripts/gen_app_icons.py from .github/assets/apps/*.png. Do not edit."
WHITE = (255, 255, 255, 255)
STEP = (8, 4, 8)   # one RGB565 step per channel, in 8-bit units


def art(bands, base=WHITE, size=512) -> Image.Image:
    """A square RGBA image of `base` with horizontal bands from the top: [(rgba, fraction of the image), ...]."""
    im = Image.new("RGBA", (size, size), base)
    y = 0
    for rgba, fraction in bands:
        rows = round(fraction * size)
        im.paste(Image.new("RGBA", (size, rows), rgba), (0, y))
        y += rows
    return im


def within_a_step_of_half(bottom: int, top: int) -> bool:
    half = [c // 2 for c in gen.decode565(top)]
    return all(abs(b - h) <= s for b, h, s in zip(gen.decode565(bottom), half, STEP))


def lookup(c_path: Path, inc: Path, present: list, absent: list) -> None:
    """Compiles a small C program against c_path and runs it: each present id has both icons, each absent one is NULL."""
    lit = lambda i: "NULL" if i is None else '"%s"' % i
    checks = []
    for i in present:
        checks.append(f"    s = pod_app_style({lit(i)});\n"
                      "    if (!s || !s->icon72 || !s->icon44 || s->icon72->size != 72 || s->icon44->size != 44 ||\n"
                      "        !s->icon72->rgb565 || !s->icon72->alpha || !s->icon44->rgb565 || !s->icon44->alpha)\n"
                      f"        return bad({lit(i)});")
    for i in absent:
        checks.append(f"    if (pod_app_style({lit(i)})) return bad({lit(i)});")
    with tempfile.TemporaryDirectory() as d:
        main = Path(d) / "main.c"
        main.write_text('#include <stdio.h>\n#include "app_icons.h"\n'
                        'static int bad(const char *id) { printf("pod_app_style is wrong for %s\\n", id ? id : "NULL"); return 1; }\n'
                        "int main(void) {\n    const pod_app_style_t *s = NULL;\n    (void)s;\n" + "\n".join(checks) +
                        "\n    return 0;\n}\n")
        exe = Path(d) / "lookup"
        cc = subprocess.run(["cc", "-std=c11", "-Wall", "-Wextra", "-Werror", f"-I{inc}", "-o", str(exe), str(main),
                             str(c_path)], capture_output=True, text=True)
        if cc.returncode:
            raise AssertionError("lookup program does not compile:\n" + cc.stderr)
        run = subprocess.run([str(exe)], capture_output=True, text=True)
        if run.returncode:
            raise AssertionError(run.stdout + run.stderr)


class GeneratorTests(unittest.TestCase):
    def test_saturated_colour_wins(self):
        self.assertEqual(gen.measure(art([((0x1F, 0x9C, 0xF0, 255), 0.30)])), (0x1F, 0x9C, 0xF0))

    def test_few_saturated_pixels_fall_to_dark_mark(self):
        im = art([((0xFF, 0, 0, 255), 0.05), ((0x30, 0x34, 0x38, 255), 0.20)])
        self.assertEqual(gen.measure(im), (0x30, 0x34, 0x38))

    def test_all_light_icon_is_the_pros_dark(self):
        self.assertEqual(gen.measure(art([], base=(0xF0, 0xF0, 0xF0, 255))), gen.PRO_DARK)

    def test_shadow_is_not_measured(self):
        im = art([((0x30, 0x34, 0x38, 255), 0.20), ((0xFF, 0, 0, 200), 0.40)])
        self.assertEqual(gen.measure(im), (0x30, 0x34, 0x38))

    def test_near_black_is_lifted(self):
        for black in ((0, 0, 0), (0x14, 0x14, 0x14), (0x14, 0x12, 0x0B)):
            self.assertEqual(gen.card_colours(black)[0], gen.encode565(gen.CHARCOAL), black)
        self.assertEqual(gen.card_colours((0x2C, 0x2E, 0x3A))[0], gen.encode565((0x2C, 0x2E, 0x3A)))

    def test_darkened_just_enough(self):
        for measured, want in (((0x1F, 0x9C, 0xF0), (0x18, 0x79, 0xBD)), ((0xD9, 0x76, 0x56), (0xAD, 0x5D, 0x42))):
            top = gen.decode565(gen.card_colours(measured)[0])
            self.assertEqual(top, want, measured)
            self.assertGreaterEqual(gen.contrast_white(top), 4.5)
            self.assertLess(gen.contrast_white(top), 5.0)

    def test_every_colour_reads(self):
        for r in range(0, 256, 17):
            for g in range(0, 256, 17):
                for b in range(0, 256, 17):
                    top, bottom = gen.card_colours((r, g, b))
                    self.assertGreaterEqual(gen.contrast_white(gen.decode565(top)), 4.5, (r, g, b))
                    self.assertGreaterEqual(gen.contrast_white(gen.decode565(bottom)), 4.5, (r, g, b))
                    self.assertTrue(within_a_step_of_half(bottom, top), (r, g, b))

    def test_shadow_is_cleared_and_cropped(self):
        im = Image.new("RGBA", (512, 512), (0, 0, 0, 0))
        im.paste(Image.new("RGBA", (480, 480), (0, 0, 0, 40)), (16, 16))   # the drop shadow's ring, 40 px wide
        im.paste(Image.new("RGBA", (400, 400), (0x1F, 0x9C, 0xF0, 255)), (56, 56))
        for s in gen.SIZES:
            px, alpha = gen.icon(im, s)
            self.assertEqual((len(px), len(alpha)), (s * s, s * s))
            self.assertFalse([a for a in alpha if 0 < a < 64], s)
            mid = s // 2
            for x, y in ((mid, 0), (mid, s - 1), (0, mid), (s - 1, mid)):
                self.assertGreaterEqual(alpha[y * s + x], 128, (s, x, y))

    def test_unknown_art_is_refused(self):
        with tempfile.TemporaryDirectory() as d:
            art([((0x2C, 0x2E, 0x3A, 255), 0.5)]).save(Path(d) / "chatgpt.png")
            with self.assertRaisesRegex(ValueError, r"chatgpt\.png"):
                gen.render(Path(d))

    def test_render_compiles_and_looks_up(self):
        with tempfile.TemporaryDirectory() as d:
            src, out = Path(d) / "src", Path(d) / "out"
            src.mkdir()
            out.mkdir()
            art([((0x1F, 0x9C, 0xF0, 255), 0.30)]).save(src / "vscode.png")
            # A source smaller than 512 is baked as given (the vendor's largest, never upscaled).
            art([((0x14, 0x14, 0x14, 255), 0.60)], size=128).save(src / "terminal-app.png")
            c, h = gen.render(src)
            (out / "app_icons.c").write_text(c)
            (out / "app_icons.h").write_text(h)
            self.assertIn("a_terminal_app_72_px[5184]", c)
            self.assertTrue(c.startswith(HEADER + "\n"))
            self.assertTrue(h.startswith(HEADER + "\n"))
            lookup(out / "app_icons.c", out, present=["vscode", "terminal-app"],
                   absent=["claude", "rex", "nope", "", "harness", "terminal", None])

    def test_check_mode(self):
        with tempfile.TemporaryDirectory() as d:
            src, out, empty = Path(d) / "src", Path(d) / "out", Path(d) / "empty"
            for p in (src, out, empty):
                p.mkdir()
            art([((0xD9, 0x76, 0x56, 255), 0.30)]).save(src / "claude.png")
            with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
                self.assertEqual(gen.main([], src, out), 0)
                self.assertEqual(gen.main(["--check"], src, out), 0)
                with open(out / "app_icons.c", "a") as f:
                    f.write(" ")
                self.assertEqual(gen.main(["--check"], src, out), 1)
                self.assertEqual(gen.main(["--check"], src, empty), 1)


if __name__ == "__main__":
    unittest.main()
