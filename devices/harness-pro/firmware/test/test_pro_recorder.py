"""The recorder's real capture and sender threads (audio/pro_recorder.c), offline: what the daemon hears about a
discarded clip. One voice.abort per discard, naming that clip, before the next clip's voice.begin; none for a clip
already closed, an older one, no clip, or a dead cable.

The audio is generated bytes in host RAM, never a microphone or a cable. SANITIZERS=thread runs it under
ThreadSanitizer.
"""
