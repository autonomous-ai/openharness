#!/usr/bin/env python3
"""Original ASCII portraits for the gallery, inspired by terminal-art traditions.

These are new drawings, not copied cowsay/Joan Stark/Nyan Cat assets.
Six poses per creature: two calm, two playful, two asleep. % = eye, ? = mouth.
Everything emitted is printable ASCII. See prototype/habitat/CREATURE_GALLERY.md.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
COLS, ROWS = 25, 9
portraits = []

def add(name, lines, alternate, play_a, play_b, sleep_a, sleep_b):
    base = lines.splitlines()
    assert len(base) <= ROWS
    base += [''] * (ROWS - len(base))
    poses = [base]
    for patch in (alternate, play_a, play_b, sleep_a, sleep_b):
        pose = base.copy()
        for row, value in patch.items():
            pose[row] = value
        poses.append(pose)
    for pose in poses:
        for line in pose:
            assert len(line) <= COLS, (name, len(line), line)
            assert all(32 <= ord(c) <= 126 for c in line)
        assert sum(row.count('%') for row in pose) == 2, (name, pose)
    portraits.append((name, poses))

