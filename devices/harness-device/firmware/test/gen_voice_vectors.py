#!/usr/bin/env python3
"""Generate the shared voice gate vectors.

    devices/harness-device/firmware/test/gen_voice_vectors.py          # writes vectors/voice_gate.txt and .pcm
    devices/harness-device/firmware/test/gen_voice_vectors.py --check  # fails if either file is missing or stale

The dial's gate (main/voice_buffer.c) and the daemon's copy of it (cli/src/cable/voiceLevel.ts) both assert against
these files. The gate below is a THIRD one, written from the description and from nothing else, so a misreading
the two halves share shows up as a disagreement with the vectors instead of being blessed by two copies of each other:
10 ms blocks of rate // 100 samples, a block loud when its integer mean |sample| is over the gain's loud level, and
the voice heard once rate * 320 // 1000 samples of loud blocks run unbroken.

The clips are synthetic (voice_signal.py): no recorded voice is in the repo.
"""

import argparse
import pathlib
import struct
import sys

# Under `python3 -I` the script's own folder is not on the path, and voice_signal.py lives beside it.
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import voice_signal  # noqa: E402

# 37.5 dB: the gate and the meter's steps as set by ear. 30 dB: the design doc's gate of 250 (the formula gives 253)
# and each 37.5 dB step scaled by 10^(-7.5/20).
STEPS_37 = (64, 180, 500, 1600)
GAINS = (
    (37.5, 600, STEPS_37),
    (30, 250, tuple(round(s * voice_signal.scale(30)) for s in STEPS_37)),
)

# The story each clip tells: heard at each gain, in GAINS' order, and whether any sample sits at full scale.
STORY = {
    'speech37': ((True, True), False),
    'speech30': ((False, True), False),  # the 600 gate misses quiet speech at 30 dB; the 250 gate hears it
    'loud37': ((True, True), True),
    'loud30': ((True, True), False),  # the lower gain frees what clipped at 37.5 dB
    'noise37': ((False, False), False),
    'noise30': ((False, False), False),
    'tap37': ((False, False), True),  # a touch thump clips but is too short to be heard
}

HERE = pathlib.Path(__file__).resolve().parent
TXT = HERE / 'vectors' / 'voice_gate.txt'
PCM = HERE / 'vectors' / 'voice_gate.pcm'


def heard(pcm, rate, loud):
    block = rate // 100
    assert len(pcm) % block == 0, 'a clip is whole 10 ms blocks'
    run = 0
    for start in range(0, len(pcm), block):
        if sum(abs(v) for v in pcm[start:start + block]) // block > loud:
            run += block
        else:
            run = 0
        if run >= rate * 320 // 1000:
            return True
    return False


def build():
    rate = voice_signal.RATE
    clips = voice_signal.clips()
    assert list(clips) == list(STORY), 'every clip has a story'
    for name, pcm in clips.items():
        got = (tuple(heard(pcm, rate, loud) for _, loud, _ in GAINS), any(v in (32767, -32768) for v in pcm))
        if got != STORY[name]:
            raise SystemExit(f'{name}: heard and full scale are {got}, the story says {STORY[name]}')
    out = [
        '# Shared voice gate vectors: the heard each 10 ms block gate must reach at each mic gain.',
        '# Generated by devices/harness-device/firmware/test/gen_voice_vectors.py from the synthetic signal in',
        '# voice_signal.py: no recorded voice. Do not hand-edit. devices/harness-device/firmware/main/voice_buffer.c',
        '# and cli/src/cable/voiceLevel.ts are both held to this file and to voice_gate.pcm (16-bit little-endian mono,',
        '# the clips back to back).',
        '#',
        '#   rate  <samples a second>',
        '#   gain  <dB>  <loud>  <step1>  <step2>  <step3>  <step4>',
        '#   clip  <name>  <first sample>  <samples>  <heard at each gain, in the gain lines\' order>',
        '',
        f'rate\t{rate}',
    ]
    for gain, loud, steps in GAINS:
        out.append('\t'.join(['gain', f'{gain:g}', str(loud), *map(str, steps)]))
    first = 0
    samples = []
    for name, pcm in clips.items():
        marks = [str(int(h)) for h in STORY[name][0]]
        out.append('\t'.join(['clip', name, str(first), str(len(pcm)), *marks]))
        first += len(pcm)
        samples += pcm
    out.append('')
    return '\n'.join(out).encode(), struct.pack(f'<{len(samples)}h', *samples)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true', help='exit non-zero if a file on disk is missing or differs')
    args = ap.parse_args()
    if args.check:
        for path in (TXT, PCM):
            if not path.exists():
                print(f'missing: {path}', file=sys.stderr)
                return 1
    files = dict(zip((TXT, PCM), build()))
    if args.check:
        for path, data in files.items():
            if path.read_bytes() != data:
                print(f'stale: {path}: re-run {pathlib.Path(__file__).name}', file=sys.stderr)
                return 1
            print(f'up to date: {path}')
        return 0
    TXT.parent.mkdir(parents=True, exist_ok=True)
    for path, data in files.items():
        path.write_bytes(data)
    print(f'wrote {TXT}')
    print(f'wrote {PCM} ({len(files[PCM])} bytes)')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
