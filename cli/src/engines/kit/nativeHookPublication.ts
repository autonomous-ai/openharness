/** Core owns native destinations and publication. Setup supplies only bounded replacement bytes. */
import { randomUUID } from 'node:crypto'
import { lstatSync } from 'node:fs'
import type { NativeSetup } from './nativeSetup.js'
import { boundedHookInput, hookCandidate, type NativeHookInput } from './nativeHookWire.js'
import { HookPreparationHeld, hookPreparationRoutes, inspectHookFile, prepareHookDirectory, runHookPreparation,
  type HookPreparationAttempt, type HookPreparationOptions, type HookPreparationProof } from './nativeHookFiles.js'

export interface NativeHookDestination {
  file: string
  mode?: number
  parentMode?: number
  /** Identical generated bytes shared by independently reserved profiles. */
  shared?: true
}

export async function publishNativeHookFiles(input: Omit<NativeHookInput, 'files'>, destinations: readonly NativeHookDestination[],
  setup: Pick<NativeSetup, 'prepareFiles'>, options: HookPreparationOptions = {}): Promise<boolean> {
  if (!setup.prepareFiles || !destinations.length || destinations.length > 4 || destinations.every(file => file.shared)) return false
  try {
    const routes = hookPreparationRoutes([...destinations.map(file => file.file), ...(input.directories ?? []).map(directory => directory.path)])
    const sharedProofs: HookPreparationProof[] = [], proofs: HookPreparationProof[] = []
    const current = () => {
      try { routes.verify(); return options.current?.() !== false && sharedProofs.every(proof => proof.current()) } catch { return false }
    }
    const installed = await runHookPreparation(destinations.filter(file => !file.shared).map(file => file.file), async attempt => {
      const observed = destinations.map(file => inspectHookFile(file.file, file.mode))
      const captured: NativeHookInput = { ...input, files: observed.map((file, index) => ({ file: destinations[index].file,
        directory: file.directory, content: file.content, mode: file.mode,
        ...(file.content === null ? {} : { alias: lstatSync(destinations[index].file).isSymbolicLink() }),
      })) }
      if (!boundedHookInput(captured)) throw new HookPreparationHeld('the hook preparation exceeds its input limits')
      const active = () => { try { attempt.verify(); return current() } catch { return false } }
      const candidate = hookCandidate(await setup.prepareFiles!(captured, randomUUID(), active), destinations.length)
      attempt.verify()
      if (!candidate || destinations.some((destination, index) => destination.shared && candidate.files[index].content === null) || !active()) throw new HookPreparationHeld('the hook preparation is unavailable or its owner changed')
      // Every profile destination is preflighted before any publication, including the shared artifact.
      for (const [index, destination] of destinations.entries()) if (!destination.shared) observed[index].prepare(candidate.files[index].content)
      const publish = async (index: number, publication: HookPreparationAttempt, shared = false) => {
        publication.verify()
        const destination = destinations[index], next = candidate.files[index].content
        const before = shared ? inspectHookFile(destination.file, destination.mode) : observed[index]
        // Another profile may have just published these exact shared bytes. Anything else is stale input.
        if (shared && before.content !== next) observed[index].verify()
        before.prepare(next)
        if (next !== null && before.content !== next && destination.parentMode !== undefined) {
          prepareHookDirectory(before.directory, publication, destination.parentMode)
        }
        const result = next === null ? await before.remove(publication) : await before.replace(next, publication)
        result.verify()
      }
      for (const [index, destination] of destinations.entries()) if (destination.shared) {
        await runHookPreparation([destination.file], async shared => { await publish(index, shared, true) }, {
          current: active, timeoutMs: options.timeoutMs, identity: JSON.stringify(candidate.files[index].content),
          confirmed: proof => sharedProofs.push(proof),
        })
        attempt.verify()
      }
      if (candidate.files.some((file, index) => file.content !== observed[index].content)) for (const directory of input.directories ?? []) {
        attempt.verify()
        const path = hookPreparationRoutes([directory.path]).keys[0]
        prepareHookDirectory(path, attempt, directory.mode)
      }
      for (const [index, destination] of destinations.entries()) if (!destination.shared) await publish(index, attempt)
      return { shared: [...sharedProofs] }
    }, { ...options, current, confirmed: proof => proofs.push(proof) })
    // A same-profile join shares the completed artifact publication too, never just its profile proof.
    for (const proof of installed.shared) if (!sharedProofs.includes(proof)) sharedProofs.push(proof)
    if (!current()) return false
    const all = [...sharedProofs, ...proofs]
    const proof: HookPreparationProof = { files: all.flatMap(proof => proof.files), current: () => {
      try { routes.verify(); return all.every(proof => proof.current()) } catch { return false }
    } }
    if (!proof.current()) return false
    options.confirmed?.(proof)
    return true
  } catch {
    console.warn('[hooks] NATIVE_HOOK_PREPARATION_HELD')
    return false
  }
}
